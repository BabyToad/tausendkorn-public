"""Data for the animated web deck: clean photos plus the real Argon v1.0.2 points, tiles and
check spots, normalised to the cropped photo, written as pitch/web/data.js (works offline
from file://, no fetch).

    uv run --no-project --with pillow python pitch/build_web_data.py
"""

import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "corn1000" / "data"
RUNS = ROOT / "results" / "argon_v1.0.2"
WEB = ROOT / "pitch" / "web"
(WEB / "img").mkdir(parents=True, exist_ok=True)


def load(split, name, run):
    res = json.loads((RUNS / run / f"{name.replace('/', '__')}.json").read_text())
    img = ImageOps.exif_transpose(Image.open(DATA / split / name)).convert("RGB")
    return img, res


def crop_export(img, res, box, fname, width):
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    out = img.crop(box).resize((width, round(width * h / w)), Image.LANCZOS)
    out.save(WEB / "img" / fname, quality=84)
    nx = lambda x: round((x - x0) / w, 4)
    ny = lambda y: round((y - y0) / h, 4)
    pts = [[nx(x), ny(y)] for x, y in res["points"] if x0 <= x <= x1 and y0 <= y <= y1]
    tiles = []
    for t in res.get("first_pass", {}).get("tiles", []):
        a, b, c, d = t["core"]
        a, b, c, d = max(a, x0), max(b, y0), min(c, x1), min(d, y1)
        if c > a and d > b:
            tiles.append([nx(a), ny(b), nx(c), ny(d), t["pred"]])
    checks = [{"box": [nx(c["region"][0]), ny(c["region"][1]), nx(c["region"][2]), ny(c["region"][3])],
               "comment": c.get("comment", "")} for c in res.get("check_here", [])]
    print(fname, out.size, len(pts), "points", len(tiles), "tiles", len(checks), "checks")
    return {"img": f"img/{fname}", "aspect": round(w / h, 4), "points": pts, "tiles": tiles,
            "checks": checks, "count": res["count"], "true": res["true"]}


def sheet_box(res, pad, aspect=None):
    xs, ys = [p[0] for p in res["points"]], [p[1] for p in res["points"]]
    x0, y0, x1, y1 = min(xs) - pad, min(ys) - pad, max(xs) + pad, max(ys) + pad
    if aspect:  # widen/heighten around the centre to a fixed aspect
        cx, cy, w, h = (x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0
        if w / h < aspect: w = h * aspect
        else: h = w / aspect
        x0, y0, x1, y1 = cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2
    return tuple(int(v) for v in (x0, y0, x1, y1))


# Rye, test day (never seen in development): 997 points, label 1000, 154 tiles.
img, res = load("test", "count_1000/count_1000-002_galaxy-s23_IMG_20261026_184810.jpg", "test")
rye = crop_export(img, res, sheet_box(res, 70, aspect=4 / 3), "roggen_clean.jpg", 1600)

# Oats, holdout: 256 points vs 253, one check spot the model flagged itself.
img, res = load("train", "S02/S02-008_galaxy-s23_20261002_150020.jpg", "holdout")
rx0, ry0, rx1, ry1 = res["check_here"][0]["region"]
cx, cy, half = (rx0 + rx1) / 2, (ry0 + ry1) / 2, max(rx1 - rx0, ry1 - ry0) * 1.6
oat = crop_export(img, res, tuple(int(v) for v in (cx - half, cy - half, cx + half, cy + half)),
                  "hafer_stelle_clean.jpg", 900)
oat["count"], oat["true"] = res["count"], res["true"]

(WEB / "data.js").write_text(
    "// generated by pitch/build_web_data.py, real Argon v1.0.2 output\n"
    f"window.TK = {json.dumps({'rye': rye, 'oat': oat}, ensure_ascii=False, separators=(',', ':'))};\n",
    encoding="utf-8")
print("data.js", (WEB / "data.js").stat().st_size // 1024, "KB")
